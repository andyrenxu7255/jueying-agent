let LOCALE = { lang: 'zh-CN', zh: {}, en: {} }

function t(key) {
  const dict = LOCALE.lang === 'en' ? LOCALE.en : LOCALE.zh
  return dict[key] || key
}

function setLang(lang) {
  LOCALE.lang = lang
  localStorage.setItem('ah_lang', lang)
  const btn = document.getElementById('lang-switch')
  if (btn) btn.textContent = lang === 'en' ? '中文' : 'English'
  document.documentElement.lang = LOCALE.lang === 'en' ? 'en' : 'zh-CN'
  if (typeof window !== 'undefined') window.CONFIG_SECTIONS = null
  if (typeof refreshLocaleView === 'function') refreshLocaleView()
  else if (typeof renderApp === 'function') renderApp()
}

function initLang() {
  const saved = localStorage.getItem('ah_lang')
  if (saved === 'en') LOCALE.lang = 'en'
  document.documentElement.lang = LOCALE.lang === 'en' ? 'en' : 'zh-CN'
}

